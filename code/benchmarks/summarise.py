"""Builds results/benchmarks/README.md from the saved JSON files (never edit that file by hand)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "results", "benchmarks")


def load(name):
    with open(os.path.join(OUT, name), encoding="utf-8") as fh:
        return json.load(fh)


def kb(n):
    return f"{n / 1024:,.0f} KB" if n < 1024 * 1024 else f"{n / 1048576:,.1f} MB"


def label(r):
    return f"{r['row']} | {r['N']} | {'/'.join(map(str, r['chain']))} | 2^{r['scale_bits']}"


def main():
    sweep, browser = load("sweep.json"), load("browser.json")
    cv, mlp = load("model_cv.json"), load("mlp_cost.json")
    L = ["# Benchmark results", "",
         "Generated by `code/benchmarks/summarise.py` from the JSON files in this folder. Do not edit by hand.", "",
         "## How each test is run", "",
         "| Test | Script | What it does |", "|---|---|---|",
         "| Settings sweep | `benchmarks/sweep.py` | Python client + the real server module, every test patient (75 Cleveland, 314 Edinburgh), both layouts. **Pass** = 100% decision match **and** encrypted score within 0.01 of the plain score |",
         "| Browser benchmark | `benchmarks/browser/run_all.py` | node-seal 7.0.0 in a headless browser creates keys, encrypts and decrypts; the real server module computes. Up to 75 patients per dataset (full-key Haq run: 20). Sizes are raw bytes of what is sent (before base64) |",
         "| Model comparison | `benchmarks/model_compare.py` | 10-fold stratified cross-validation repeated 10 times; all tuning inside the training folds |",
         "| Neural network cost | `benchmarks/mlp_cost.py` | Encrypted inference of the square-activation network on the fixed test split, Python client |",
         "", "Environment (browser benchmark): "
         + f"{browser['environment']['platform']}, {browser['environment']['processor']}; client and server on one computer (no network delay).",
         "**Sizes are exact and repeatable. Times are indicative:** a repeated run on this laptop differed by up to about 2x.", ""]
    for ds in ("cleveland", "edinburgh"):
        L += [f"## Track 1: browser benchmark – {ds}", "",
              "| Config | Row | N | Chain (bits) | Scale | Layout | Mode | Upload / patient | Keys (once) | Reply | Encrypt ms | Server calc ms | Server total ms | Decrypt ms | Match | Accuracy | Patients |",
              "|---" * 17 + "|"]
        for r in browser["results"]:
            d = r["datasets"][ds]
            mode = ("browser sigmoid" if r["sigmoid"] == "browser" else "server cubic")
            extra = f"{r['encryption']}, {r['compr']}" + ("" if r["trim"] else ", reply not trimmed") + (", full rotation keys" if r["full_galois"] else "")
            keys = d["galois_key_bytes"] + d["relin_key_bytes"]
            L.append(f"| {r['id']} | {label(r)} | {r['layout']} | {mode}; {extra} | {kb(d['upload_bytes'])} | "
                     f"{kb(keys) if keys else 'none'} | {kb(d['result_bytes'])} | {d['encrypt_ms']:.0f} | {d['server_ms']:.0f} | "
                     f"{d['server_total_ms']:.0f} | {d['decrypt_ms']:.1f} | {d['decision_match']:.0%} | {d['accuracy']:.3f} | {d['patients']} |")
        L.append("")
    L += ["## Track 1: settings sweep (all test patients, Python client)", "",
          "| Mode | N | Chain | Scale | Layout | Result | Cleveland match / max error | Edinburgh match / max error |",
          "|---|---|---|---|---|---|---|---|"]
    for r in sweep["rows"]:
        def cell(ds):
            d = r["datasets"].get(ds)
            return f"{d['decision_match']:.1%} / {d['max_abs_error']:.1e}" if d else "could not compute"
        L.append(f"| {r['sigmoid']} | {r['N']} | {'/'.join(map(str, r['chain']))} | 2^{r['scale_bits']} | {r['layout']} | "
                 f"{'pass' if r['pass'] else 'fail'} | {cell('cleveland')} | {cell('edinburgh')} |")
    L += ["", "## Track 2: model comparison (repeated cross-validation)", ""]
    for ds, e in cv["datasets"].items():
        L += [f"**{ds}** ({e['rows']} rows). Spread (standard deviation of LR fold accuracies): {e['spread_lr_sd']:.4f}.", "",
              "| Model | Accuracy (mean ± sd) | ROC-AUC | Gain over LR | Gain larger than spread? |", "|---|---|---|---|---|"]
        for name, m in e["models"].items():
            L.append(f"| {name} | {m['accuracy_mean']:.4f} ± {m['accuracy_sd']:.4f} | {m['auc_mean']:.4f} | "
                     f"{m['gain_vs_lr']:+.4f} | {'–' if name == 'LR' else ('yes' if m['passes_rule_a'] else 'no')} |")
        L.append("")
    L += ["## Track 2: encrypted cost of the neural network (smallest passing setting)", "",
          "| Dataset | Layout | Setting | Upload / patient | Server calc ms | Relin keys | Rotation keys | Match |",
          "|---|---|---|---|---|---|---|---|"]
    for ds, e in mlp["datasets"].items():
        for lay, r in e["layouts"].items():
            L.append(f"| {ds} | {lay} | N={r['N']}, {'/'.join(map(str, r['chain']))}, 2^{r['scale_bits']} | {kb(r['upload_bytes'])} | "
                     f"{r['server_ms_mean']:.0f} | {kb(r['relin_key_bytes'])} | {kb(r['rotation_key_bytes']) if r['rotation_key_bytes'] else 'none'} | {r['decision_match']:.0%} |")
    L += ["", "These Python-client upload sizes use public-key encryption; compare them with the logistic-regression "
          "rows of the sweep, not with the seeded browser rows.", ""]
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print("written")


if __name__ == "__main__":
    main()
